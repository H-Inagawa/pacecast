export function prefectureFromStationId(stationId: string | null | undefined): string {
  const code = String(stationId ?? "").trim().slice(0, 2);
  return PREFECTURE_BY_CODE[code] ?? "";
}

export function prefecturesInStations(stationIds: string[]): string[] {
  const present = new Set(stationIds.map(prefectureFromStationId).filter(Boolean));
  return PREFECTURES.filter((name) => present.has(name));
}
