"use client";

import { useEffect } from "react";
import { ModalCloseButton } from "./ModalCloseButton";

type Props = {
  open: boolean;
  onClose: () => void;
};

export function CourseMethodModal({ open, onClose }: Props) {
  useEffect(() => {
    if (!open) {
      return;
    }
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    function onKeyDown(event: KeyboardEvent) {
      if (event.key === "Escape") {
        onClose();
      }
    }

    window.addEventListener("keydown", onKeyDown);
    return () => {
      document.body.style.overflow = previousOverflow;
      window.removeEventListener("keydown", onKeyDown);
    };
  }, [open, onClose]);

  if (!open) {
    return null;
  }

  return (
    <div className="modal-backdrop" onClick={onClose} role="presentation">
      <div
        className="modal-panel about-panel"
        role="dialog"
        aria-modal="true"
        aria-labelledby="course-method-title"
        onClick={(event) => event.stopPropagation()}
      >
        <ModalCloseButton onClick={onClose} />
        <h2 id="course-method-title">作成方法</h2>
        <h3>探し方</h3>
        <p>
          円、正方形、長方形のような形を先に置いて道を寄せることはしません。出発点の近くの大通り、河川敷、公園内の道を見つけ、その道を進みながら分岐を選び、出発点へ戻る周回を探します。大通りだけでは周回が閉じないときは、道の段階を一段ずつ下げ、候補が1本できるまで探します。歩道や細い道も、その順で足します。同じ探し方で、出発点から見て別の向きに進む周回も集め、向きが重ならないものを点数の高い順に最大5件出します。
        </p>
        <p>
          分岐では、まっすぐ続けられる道と、進行が時計回りから大きく反時計回りへ戻らない道を優先します。右折の回数は決めていません。大通り、河川敷、公園内の道を長く走り、細い道はそれらや出発点をつなぐ短い区間に限って通ります。スタートが細い道に面しているときも、公園の中と同じです。園内の通路や細い道からは始めず、800m以内にある大通りと河川敷を、近い順に周回の起点にします。起点は5kmまでは最大5本で、5kmを超えて3km伸びるごとに1本減らし、17km以上はいちばん近い1本だけです。起点が1本のときに足す別方向の探索も、同じ刻みで減らし、17km以上は足しません。各起点では、出発した向きに加えて逆向きも探します。選んだ地点からその道までの距離は、コースごとに表へ出しますが、点数には入れません。
        </p>
        <p>同じ探し方でも、分岐の選び方を少し変えて、条件を満たす周回を最大50件集めます。ほぼ同じ線は1本にまとめ、点数の高い順に最大5件を出します。</p>

        <h3>残す条件</h3>
        <p>
          出発点に戻らない案は出しません。距離は、指定の±20%から外れる案を除きます。5kmならおよそ4〜6kmです。道路の重複が全距離の10%を超える案も除きます。ただし、出発点から周回までの同じ道は、その先で分かれて周回になるなら重複に数えません。合格が無いときは、距離が最も近い案と、距離は合って重複が多い案を1件ずつ表示します。曲がってすぐ元の道へ戻る短い往復は、まっすぐな道に直してから距離と重複を見ます。曲がり角、細い道、Uターン、時計回りからのずれは、除かずに点数を下げます。
        </p>
        <p>50件に達した時点で、それ以上の分岐は探しません。ほぼ同じ線は1本にまとめます。</p>

        <h3>点数</h3>
        <p>
          いちばん重く見るのは、走りやすい道の長さです。大通り、河川敷、公園内の道を走った距離を合わせて、全距離がそうなら満点です。その次に指定距離との差、その次に直進、曲がりの少なさ、細い道の短さ、同じ道を往復しないことです。時計回りらしさとUターンの少なさは、そのあとです。曲がりは実距離1kmあたり1か所以下なら満点、3回で0点です。往復は0%なら満点、10%で0点で、10%を超える案は除きます。交差点、上り、下り、信号、付近の道までの距離は点数に入れません。画面に出す点数は、今回の候補でいちばん高い素点を100点にした相対評価です。
        </p>
        <p>走りやすい道が短く、曲がりや往復や細い道が多い案は下がります。</p>

        <h3>画面の数字</h3>
        <p>
          予想ペースと予想タイムは出しません。地図の下に、距離・評価・実スコアと内訳の表を出します。コース名のボタンを押すと、地図に出す線が切り替わります。評価は今回のいちばん高い実スコアを100点にしたものです。各項目のカッコ内は実スコアです。右上の「採点基準」に配点を出します。走りやすい道は、大通り、河川敷、公園内の道を走った距離です。道路重複は、逆方向に同じ場所を走る距離の割合です。高低差は標高データから出します。
        </p>
        <p>コースは保存しません。作成には数分かかることがあります。検索中は「検索を中止」で止められます。</p>
        <p>道路データの公開サービスが混み合っているときは、1〜2分待ってからもう一度作成してください。そのとき、すでに出ている候補はそのまま表示します。</p>
      </div>
    </div>
  );
}
