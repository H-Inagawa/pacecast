"use client";

import { useEffect } from "react";
import { ModalCloseButton } from "./ModalCloseButton";

type Props = {
  open: boolean;
  onClose: () => void;
};

export function CourseMethodModal({ open, onClose }: Props) {
  useEffect(() => {
    if (!open) {
      return;
    }
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    function onKeyDown(event: KeyboardEvent) {
      if (event.key === "Escape") {
        onClose();
      }
    }

    window.addEventListener("keydown", onKeyDown);
    return () => {
      document.body.style.overflow = previousOverflow;
      window.removeEventListener("keydown", onKeyDown);
    };
  }, [open, onClose]);

  if (!open) {
    return null;
  }

  return (
    <div className="modal-backdrop" onClick={onClose} role="presentation">
      <div
        className="modal-panel about-panel"
        role="dialog"
        aria-modal="true"
        aria-labelledby="course-method-title"
        onClick={(event) => event.stopPropagation()}
      >
        <ModalCloseButton onClick={onClose} />
        <h2 id="course-method-title">作成方法</h2>
        <h3>探し方</h3>
        <p>
          円、正方形、長方形のような形を先に置いて道を寄せることはしません。OpenStreetMap 上の歩道付きの道（歩道タグ付き、または独立歩道が隣接する道）、歩行者・自転車が通れる道、公園内の通路、河川敷の経路をつないだネットワークから、出発点へ戻る周回を探します。独立歩道そのものはルートに入れず、隣の車道を歩道付きとして扱います。走りやすい道だけでは周回が閉じないときは、生活道路などの歩行可能な道を接続道路として足して探します。接続道路を長く使う案は点数を下げます。同じ探し方で、出発点から見て別の向きに進む周回も集め、向きが重ならないものを点数の高い順に最大5件出します。
        </p>
        <p>
          分岐では、まっすぐ続けられる道と、これまでの曲がりと同じ向きの道を優先します（往復して戻るロリポップ型より、一周する周回を拾いやすくします）。出発から約800m以内は分岐を絞り込まず探し、それ以降は上位の道に絞ります。公園の縁や堀・河川沿いの道は、ごく弱く優遇します。右折の回数は決めていません。直前の道を180度引き返すUターンはしません。同じ道を周回のあとで再利用して戻るのは構いません。スタートは、面している細い道や公園内の通路を含む、いちばん近い走りやすい道または接続道路から始めます。広場や山奥など、近くにスタートできる道が無いときは、理由と起点の移動案内を出します。別方向の探索は距離が長いほど減らし、17km以上は足しません。出発した向きに加えて逆向きも探します。
        </p>
        <p>同じ探し方でも、分岐の選び方を少し変えて、条件を満たす周回を最大50件集めます。ほぼ同じ線は1本にまとめ、点数の高い順に最大5件を出します。</p>

        <h3>残す条件</h3>
        <p>
          出発点に戻らない案は出しません。距離は、指定の±20%から外れる案を除きます。5kmならおよそ4〜6kmです。道路の重複が全距離の10%を超える案、細い道が全距離の40%を超える案も除きます。ただし、出発点から周回までの同じ道は、その先で分かれて周回になるなら重複に数えません。合格が無いときは、距離が最も近い案と、距離は合って重複が多い案を1件ずつ表示します。曲がってすぐ元の道へ戻る短い往復は、まっすぐな道に直してから距離と重複を見ます。信号、曲がり角、細い道は、除かずに点数を下げます。
        </p>
        <p>50件に達した時点で、それ以上の分岐は探しません。ほぼ同じ線は1本にまとめます。</p>

        <h3>点数</h3>
        <p>
          指定距離との差、走りやすい道の割合、細い道の短さをそれぞれ20点で見ます。その次に直進、信号の少なさ、曲がり角の少なさ、同じ道を往復しないことが各10点です。細い道は全距離の25%で0点です。信号は実距離1kmあたり5回で0点、曲がり角は1kmあたり3か所で0点です。往復は0%なら満点、10%で0点で、10%を超える案は除きます。交差点、上り、下り、時計回り、Uターンは点数に入れません。画面に出す点数は、今回の候補でいちばん高い素点を100点にした相対評価で、点数の高い順に並べます。
        </p>
        <p>走りやすい道が短く、細い道や信号や曲がり角や往復が多い案は下がります。</p>

        <h3>画面の数字</h3>
        <p>
          予想ペースと予想タイムは出しません。地図の下に、距離・評価・実スコアと内訳の表を出します。コース名のボタンを押すと、地図に出す線が切り替わります。評価は今回のいちばん高い実スコアを100点にしたものです。各項目のカッコ内は実スコアです。右上の「採点基準」に配点を出します。走りやすい道は、歩道や河川敷、公園内の通路などを走った距離です。道路重複は、逆方向に同じ場所を走る距離の割合です。高低差は標高データから出します。
        </p>
        <p>コースは保存しません。作成には数分かかることがあります。検索中は「検索を中止」で止められます。</p>
        <p>道路データの公開サービスが混み合っているときは、1〜2分待ってからもう一度作成してください。そのとき、すでに出ている候補はそのまま表示します。</p>
      </div>
    </div>
  );
}
